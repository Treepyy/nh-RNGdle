export function getTagScore(count: number) {
  if (!count || count === 0) return 1;
  // Inverse scoring: lower count = exponentially higher score
  return Math.max(1, Math.round(100000 / count));
}

export function getRarityColor(count: number) {
  if (count < 100) return 'text-yellow-400 border-yellow-400 shadow-[0_0_10px_rgba(250,204,21,0.8)]'; // Legendary
  if (count < 1000) return 'text-purple-400 border-purple-400 shadow-[0_0_8px_rgba(192,132,252,0.8)]'; // Epic
  if (count < 10000) return 'text-blue-400 border-blue-400 shadow-[0_0_5px_rgba(96,165,250,0.6)]'; // Rare
  if (count < 50000) return 'text-green-400 border-green-400'; // Uncommon
  return 'text-gray-300 border-gray-600'; // Common
}